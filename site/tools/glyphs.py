# Extracts the window-letter outlines from the self-hosted Noto Serif Hebrew variable font at the display instance
# (wght 900 / wdth 62.5), plus a measured "roof" box (the thick top stroke) used as the zoom's transform origin.
# Output: lib/glyphs.ts (checked in; the window never depends on font loading). Run: python3 -I tools/glyphs.py
import json, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.basePen import decomposeQuadraticSegment

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'public/fonts/noto-serif-hebrew-var-hebrew.woff2')
INSTANCE = {"wght": 900, "wdth": 62.5}
LETTERS = ['ם', 'ה', 'ת', 'ח', 'ד', 'ר', 'מ', 'ן', 'כ', 'ב', 'ך']

f = TTFont(SRC)
inst = instantiateVariableFont(f, INSTANCE)
gs = inst.getGlyphSet()
cmap = inst.getBestCmap()
upem = inst['head'].unitsPerEm
hhea = inst['hhea']; os2 = inst['OS/2']
meta = {"instance": INSTANCE, "unitsPerEm": upem, "ascent": hhea.ascent, "descent": hhea.descent, "typoAscent": os2.sTypoAscender, "typoDescent": os2.sTypoDescender, "capHeight": getattr(os2, 'sCapHeight', 0), "xHeight": getattr(os2, 'sxHeight', 0)}
print('font meta', meta, file=sys.stderr)

def flatten(rec):
    polys = []; cur = None; x = y = 0.0
    def push(px, py):
        nonlocal x, y; cur.append((px, py)); x, y = px, py
    for op, args in rec.value:
        if op == 'moveTo': cur = []; polys.append(cur); push(*args[0])
        elif op == 'lineTo': push(*args[0])
        elif op == 'qCurveTo':
            pts = list(args)
            if pts[-1] is None: pts = pts[:-1]
            for (c, e) in decomposeQuadraticSegment(pts):
                sx, sy = x, y
                for t in range(1, 9):
                    u = t / 8.0
                    push((1-u)*(1-u)*sx + 2*(1-u)*u*c[0] + u*u*e[0], (1-u)*(1-u)*sy + 2*(1-u)*u*c[1] + u*u*e[1])
        elif op == 'curveTo':
            c1, c2, e = args; sx, sy = x, y
            for t in range(1, 11):
                u = t / 10.0; v = 1 - u
                push(v*v*v*sx + 3*v*v*u*c1[0] + 3*v*u*u*c2[0] + u*u*u*e[0], v*v*v*sy + 3*v*v*u*c1[1] + 3*v*u*u*c2[1] + u*u*u*e[1])
        elif op in ('closePath', 'endPath'): cur = None
    return polys

def spans(polys, sy):
    xs = []
    for poly in polys:
        n = len(poly)
        for i in range(n):
            x1, y1 = poly[i]; x2, y2 = poly[(i + 1) % n]
            if (y1 <= sy < y2) or (y2 <= sy < y1):
                t = (sy - y1) / (y2 - y1); xs.append((x1 + t * (x2 - x1), 1 if y2 > y1 else -1))
    xs.sort()
    out = []; wind = 0; start = 0
    for x, w in xs:
        before = wind; wind += w
        if before == 0 and wind != 0: start = x
        elif before != 0 and wind == 0: out.append((start, x))
    return out

glyphs = {}
for ch in LETTERS:
    gname = cmap[ord(ch)]
    g = gs[gname]
    svg = SVGPathPen(gs); g.draw(svg); d = svg.getCommands()
    rec = RecordingPen(); g.draw(rec)
    polys = flatten(rec)
    xs = [p[0] for poly in polys for p in poly]; ys = [p[1] for poly in polys for p in poly]
    minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)
    width = maxx - minx
    roof_top = None; roof_bottom = None
    sy = maxy - 2
    while sy > miny:
        sp = spans(polys, sy)
        widest = max([b - a for a, b in sp], default=0)
        covered = widest / width if width else 0
        if roof_top is None and covered >= 0.8: roof_top = sy
        if roof_top is not None and covered < 0.8: roof_bottom = sy + 4; break
        sy -= 4
    if roof_top is None: roof_top = maxy; roof_bottom = maxy - (maxy - miny) * 0.25
    if roof_bottom is None: roof_bottom = miny
    mid = (roof_top + roof_bottom) / 2
    sp = sorted(spans(polys, mid), key=lambda ab: ab[1] - ab[0], reverse=True)
    rx0, rx1 = sp[0] if sp else (minx, maxx)
    adv = inst['hmtx'][gname][0]
    glyphs[ch] = {"advance": adv, "bbox": {"x": round(minx, 1), "y": round(miny, 1), "w": round(width, 1), "h": round(maxy - miny, 1)},
                  "roof": {"x": round(rx0, 1), "y": round(roof_bottom, 1), "w": round(rx1 - rx0, 1), "h": round(roof_top - roof_bottom, 1)}, "d": d}
    print(ch, gname, 'adv', adv, 'bbox', glyphs[ch]['bbox'], 'roof', glyphs[ch]['roof'], 'dlen', len(d), file=sys.stderr)

ts = ("/* AUTO-GENERATED by tools/glyphs.py from public/fonts/noto-serif-hebrew-var-hebrew.woff2 at the display instance %s.\n"
      " * Coordinates are font units, Y UP (font space), origin at the pen position on the baseline. Draw with ctx.transform(s,0,0,-s,x,baselineY). Do not edit. */\n"
      "export type GlyphBox = { x: number; y: number; w: number; h: number };\n"
      "export type WindowGlyph = { advance: number; bbox: GlyphBox; roof: GlyphBox; d: string };\n"
      "export const GLYPH_FONT = %s as const;\n"
      "export const GLYPHS: Record<string, WindowGlyph> = %s;\n") % (json.dumps(INSTANCE), json.dumps(meta), json.dumps(glyphs, ensure_ascii=False, indent=1))
open(os.path.join(ROOT, 'lib/glyphs.ts'), 'w', encoding='utf-8').write(ts)
print('wrote lib/glyphs.ts', len(ts), file=sys.stderr)
