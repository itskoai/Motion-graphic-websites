// Extracts the window-letter outlines from the self-hosted Noto Serif Hebrew variable font at the exact display instance,
// plus a measured "roof" box (the thick top stroke) that the zoom uses as its transform origin.
// Output: lib/glyphs.ts (checked in; the window never depends on font loading).
import * as fontkit from 'fontkit';
import fs from 'node:fs';

const SRC = 'public/fonts/noto-serif-hebrew-var-hebrew.woff2';
const INSTANCE = { wght: 900, wdth: 62.5 };
const LETTERS = ['ם', 'ה', 'ת', 'ח', 'ד', 'ר', 'מ', 'ן', 'כ', 'ב'];

const font = fontkit.openSync(SRC);
console.error('font:', font.familyName, 'upem', font.unitsPerEm, 'ascent', font.ascent, 'descent', font.descent, 'axes', JSON.stringify(font.variationAxes));
const inst = font.getVariation(INSTANCE);

// Flatten a fontkit path into polygons (y up, glyph units)
function flatten(path) {
  const polys = []; let cur = null; let x = 0, y = 0;
  const push = (px, py) => { cur.push([px, py]); x = px; y = py; };
  for (const c of path.commands) {
    if (c.command === 'moveTo') { cur = []; polys.push(cur); push(c.args[0], c.args[1]); }
    else if (c.command === 'lineTo') push(c.args[0], c.args[1]);
    else if (c.command === 'quadraticCurveTo') { const [cx, cy, ex, ey] = c.args; const sx = x, sy = y; for (let t = 1; t <= 8; t++) { const u = t / 8; push((1-u)*(1-u)*sx + 2*(1-u)*u*cx + u*u*ex, (1-u)*(1-u)*sy + 2*(1-u)*u*cy + u*u*ey); } }
    else if (c.command === 'bezierCurveTo') { const [c1x, c1y, c2x, c2y, ex, ey] = c.args; const sx = x, sy = y; for (let t = 1; t <= 10; t++) { const u = t / 10, v = 1 - u; push(v*v*v*sx + 3*v*v*u*c1x + 3*v*u*u*c2x + u*u*u*ex, v*v*v*sy + 3*v*v*u*c1y + 3*v*u*u*c2y + u*u*u*ey); } }
    else if (c.command === 'closePath') { cur = null; }
  }
  return polys;
}
// Inside spans on a scanline (non-zero winding)
function spans(polys, sy) {
  const xs = [];
  for (const poly of polys) for (let i = 0; i < poly.length; i++) {
    const [x1, y1] = poly[i], [x2, y2] = poly[(i + 1) % poly.length];
    if ((y1 <= sy && y2 > sy) || (y2 <= sy && y1 > sy)) { const t = (sy - y1) / (y2 - y1); xs.push([x1 + t * (x2 - x1), y2 > y1 ? 1 : -1]); }
  }
  xs.sort((a, b) => a[0] - b[0]);
  const out = []; let wind = 0, start = 0;
  for (const [x, w] of xs) { const before = wind; wind += w; if (before === 0 && wind !== 0) start = x; else if (before !== 0 && wind === 0) out.push([start, x]); }
  return out;
}

const out = { instance: INSTANCE, unitsPerEm: font.unitsPerEm, ascent: font.ascent, descent: font.descent, glyphs: {} };
for (const ch of LETTERS) {
  const g = inst.glyphForCodePoint(ch.codePointAt(0));
  const path = g.path;
  const bbox = g.bbox; // minX, minY, maxX, maxY (y up)
  const polys = flatten(path);
  const width = bbox.maxX - bbox.minX;
  // Scan from the top down: the roof is the first band whose widest inside span covers >= 80% of the glyph width
  let roofTop = null, roofBottom = null;
  for (let sy = bbox.maxY - 2; sy > bbox.minY; sy -= 4) {
    const sp = spans(polys, sy);
    const widest = sp.reduce((m, [a, b]) => Math.max(m, b - a), 0);
    const covered = widest / width;
    if (roofTop === null && covered >= 0.8) roofTop = sy;
    if (roofTop !== null && covered < 0.8) { roofBottom = sy + 4; break; }
  }
  if (roofTop === null) { roofTop = bbox.maxY; roofBottom = bbox.maxY - (bbox.maxY - bbox.minY) * 0.25; }
  if (roofBottom === null) roofBottom = bbox.minY;
  // Horizontal extent of the roof: the widest span at the roof's middle
  const mid = (roofTop + roofBottom) / 2;
  const sp = spans(polys, mid).sort((a, b) => (b[1] - b[0]) - (a[1] - a[0]))[0] || [bbox.minX, bbox.maxX];
  // SVG path in glyph units with y flipped (y down), so it can be drawn directly with a transform
  const d = path.commands.map((c) => {
    const a = c.args.map((v, i) => (i % 2 ? -v : v)).map((v) => Math.round(v * 10) / 10);
    switch (c.command) { case 'moveTo': return `M${a[0]} ${a[1]}`; case 'lineTo': return `L${a[0]} ${a[1]}`; case 'quadraticCurveTo': return `Q${a[0]} ${a[1]} ${a[2]} ${a[3]}`; case 'bezierCurveTo': return `C${a[0]} ${a[1]} ${a[2]} ${a[3]} ${a[4]} ${a[5]}`; case 'closePath': return 'Z'; default: return ''; }
  }).join('');
  out.glyphs[ch] = {
    advance: g.advanceWidth,
    bbox: { x: bbox.minX, y: -bbox.maxY, w: width, h: bbox.maxY - bbox.minY },
    roof: { x: sp[0], y: -roofTop, w: sp[1] - sp[0], h: roofTop - roofBottom },
    d,
  };
  console.error(ch, 'adv', g.advanceWidth, 'bbox', JSON.stringify(out.glyphs[ch].bbox), 'roof', JSON.stringify(out.glyphs[ch].roof), 'cmds', path.commands.length);
}
const ts = `/* AUTO-GENERATED by tools/glyphs.mjs from ${SRC} at the display instance ${JSON.stringify(INSTANCE)}.
 * Coordinates are font units, y DOWN, origin at the pen position on the baseline. Do not edit by hand. */
export type GlyphBox = { x: number; y: number; w: number; h: number };
export type WindowGlyph = { advance: number; bbox: GlyphBox; roof: GlyphBox; d: string };
export const GLYPH_FONT = ${JSON.stringify({ instance: INSTANCE, unitsPerEm: font.unitsPerEm, ascent: font.ascent, descent: font.descent })} as const;
export const GLYPHS: Record<string, WindowGlyph> = ${JSON.stringify(out.glyphs, null, 1)};
`;
fs.writeFileSync('lib/glyphs.ts', ts);
console.error('wrote lib/glyphs.ts', ts.length, 'bytes');
